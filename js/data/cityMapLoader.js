/**
 * City-map importer.
 *
 * Turns a real road network into the same plain data the synthetic generator produces,
 * so the benchmark, the cost model and both algorithms work on it unchanged.
 *
 * ── Supported inputs ──────────────────────────────────────────────────────────
 *   1. GeoJSON            FeatureCollection / Feature / bare geometry, LineString and
 *                         MultiLineString. Extra coordinate (lon, lat, elevation) is
 *                         used when present. `properties.highway`, `properties.maxspeed`
 *                         and `properties.oneway` are understood.
 *   2. Overpass / OSM JSON  `{ elements: [ {type:'node'}, {type:'way'} ] }`, both the
 *                         `out body` form (way.nodes + separate node elements) and the
 *                         `out geom` form (way.geometry).
 *   3. CSV                Either one self-contained edge list with the endpoint
 *                         coordinates on each row, or two files: a node table
 *                         (id, lat, lon [, elevation]) and an edge table
 *                         (from, to [, length_m] [, speed_kph] [, highway] [, oneway]).
 *
 * ── What the importer does ────────────────────────────────────────────────────
 *   • Projects lon/lat to local metres (equirectangular around the map's mid-latitude).
 *     A city-sized area distorts by well under a metre, which is far below the noise
 *     floor of a routing benchmark.
 *   • Snaps vertices onto a grid (`snapMetres`, default 0.5 m) so that shared
 *     intersections become one node. Real exports usually share exact coordinates;
 *     this tolerance also stitches GIS data that is a few centimetres out.
 *   • Derives edge lengths from the geometry (a length column, when present, is ignored
 *     for consistency — every algorithm must see the same distance).
 *   • Keeps one-way streets as genuinely one-way arcs.
 *   • Fills in speed limits: from `maxspeed` / a speed column when available, otherwise
 *     the longest 20 % of roads become 60 km/h arterials and the rest 40 km/h streets.
 *   • Finds the largest connected component so the benchmark origin and destination are
 *     always reachable from one another.
 *
 * ── Deliberately NOT imported ─────────────────────────────────────────────────
 *   Traffic congestion and road closures are generated by the scenario, not read from
 *   the file, because real-time traffic is not part of a static map export. Every
 *   condition is therefore applied identically to both algorithms (see the README).
 */

