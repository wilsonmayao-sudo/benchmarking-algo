/** Column aliases, matched after stripping every non-alphanumeric character. */
const COLUMNS = {
  id: ['id', 'node', 'nodeid', 'osmid', 'index', 'nid', 'vertex', 'vertexid', 'stopid'],
  lat: ['lat', 'latitude', 'y', 'ylat', 'nodey'],
  lon: ['lon', 'lng', 'long', 'longitude', 'x', 'xlon', 'nodex'],
  elevation: ['elevation', 'elev', 'z', 'altitude', 'height', 'alt', 'elevationm'],
  from: ['from', 'u', 'source', 'src', 'start', 'fromid', 'nodea', 'a', 'fromnode', 'origin'],
  to: ['to', 'v', 'target', 'dst', 'dest', 'destination', 'end', 'toid', 'nodeb', 'b', 'tonode'],
  length: ['length', 'len', 'lengthm', 'dist', 'distance', 'distancem', 'metres', 'meters'],
  speed: ['speed', 'speedkph', 'maxspeed', 'kph', 'speedkmh', 'speedkmph', 'velocity', 'limit'],
  highway: ['highway', 'roadclass', 'class', 'type', 'category', 'roadtype'],
  oneway: ['oneway', 'directed', 'isoneway'],
  lat1: ['lat1', 'lata', 'fromlat', 'slat', 'startlat', 'originlat'],
  lon1: ['lon1', 'lona', 'fromlon', 'slon', 'startlon', 'originlon'],
  lat2: ['lat2', 'latb', 'tolat', 'elat', 'endlat', 'destlat'],
  lon2: ['lon2', 'lonb', 'tolon', 'elon', 'endlon', 'destlon'],
};

function csvFilesToLines(files, warnings) {
  const tables = files.map((file) => {
    const rows = parseCsv(file.text);
    if (rows.length < 2) throw new Error(`${file.name}: no data rows found.`);
    const header = rows[0].map(normalizeName);
    return { name: file.name, header, rows: rows.slice(1), columns: mapColumns(header) };
  });

  if (tables.length === 1) {
    const table = tables[0];
    if (hasInlineCoordinates(table.columns)) return singleEdgeTableToLines(table, warnings);
    if (table.columns.lat !== undefined && table.columns.lon !== undefined) {
      throw new Error(
        `${table.name} looks like a node table (it has coordinates but no from/to columns). ` +
        'Select the node file AND the edge file together in the file picker.',
      );
    }
    throw new Error(
      `${table.name}: could not find road endpoints. The CSV needs either ` +
      '`from,to,lat1,lon1,lat2,lon2` columns, or a from/to pair plus a separate node table.',
    );
  }

  // two or more files: find the node table and the edge table
  const nodeTable = tables.find(
    (t) => t.columns.lat !== undefined && t.columns.lon !== undefined && t.columns.from === undefined,
  ) || tables.find((t) => t.columns.lat !== undefined && t.columns.lon !== undefined);

  const edgeTable = tables.find(
    (t) => t.columns.from !== undefined && t.columns.to !== undefined && t !== nodeTable,
  );

  if (!nodeTable) {
    throw new Error(`Could not find a node table. Looked for a "lat" and "lon" column in: ${files.map((f) => f.name).join(', ')}.`);
  }
  if (!edgeTable) {
    throw new Error(`Could not find an edge table. Looked for a "from" and "to" column in: ${files.map((f) => f.name).join(', ')}.`);
  }

  return nodeEdgeTablesToLines(nodeTable, edgeTable, warnings);
}

function normalizeName(value) {
  return String(value).trim().toLowerCase().replace(/[^a-z0-9]/g, '');
}

function mapColumns(header) {
  const found = {};
  for (const [field, aliases] of Object.entries(COLUMNS)) {
    const index = header.findIndex((h) => aliases.includes(h));
    if (index >= 0) found[field] = index;
  }
  return found;
}

function hasInlineCoordinates(columns) {
  return columns.lat1 !== undefined && columns.lon1 !== undefined
    && columns.lat2 !== undefined && columns.lon2 !== undefined;
}

/** One CSV where every row is a road segment carrying its own endpoint coordinates. */
function singleEdgeTableToLines(table, warnings) {
  const { columns, rows } = table;
  const lines = [];
  const tags = [];
  let hasElevation = false;

  for (const row of rows) {
    const lat1 = Number(row[columns.lat1]);
    const lon1 = Number(row[columns.lon1]);
    const lat2 = Number(row[columns.lat2]);
    const lon2 = Number(row[columns.lon2]);
    if (![lat1, lon1, lat2, lon2].every(Number.isFinite)) continue;

    lines.push([[lon1, lat1, NaN], [lon2, lat2, NaN]]);
    tags.push(rowTags(row, columns));

    const elev = columns.elevation !== undefined ? Number(row[columns.elevation]) : NaN;
    if (Number.isFinite(elev)) hasElevation = true;
  }

  if (lines.length === 0) throw new Error(`${table.name}: no rows had valid coordinates.`);
  if (columns.length !== undefined) {
    warnings.push('The file\'s length column was ignored; distances are recomputed from the coordinates so both algorithms see identical geometry.');
  }
  return { lines, tags, hasElevation, source: 'CSV edge list' };
}

/** Classic node table + edge table pair. */
function nodeEdgeTablesToLines(nodeTable, edgeTable, warnings) {
  const { columns: nc, rows: nrows } = nodeTable;
  const { columns: ec, rows: erows } = edgeTable;

  const indexById = new Map();
  const lines = [];
  const tags = [];
  let hasElevation = nc.elevation !== undefined;

  // A node table is really a list of coordinates; wrap each node in its own
  // single-segment "line" so the shared builder can do the snapping.
  for (const row of nrows) {
    const id = row[nc.id !== undefined ? nc.id : 0];
    const lat = Number(row[nc.lat]);
    const lon = Number(row[nc.lon]);
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    const elev = nc.elevation !== undefined ? Number(row[nc.elevation]) : NaN;
    // "NaN" rather than "" so a missing elevation is not silently read back as 0.
    const packed = `${lon},${lat},${Number.isFinite(elev) ? elev : 'NaN'}`;
    indexById.set(String(id).trim(), packed);
  }
  if (indexById.size === 0) throw new Error(`${nodeTable.name}: no rows had valid coordinates.`);

  for (const row of erows) {
    const fromId = String(row[ec.from]).trim();
    const toId = String(row[ec.to]).trim();
    const a = indexById.get(fromId);
    const b = indexById.get(toId);
    if (a === undefined || b === undefined) continue;
    lines.push([a.split(',').map(Number), b.split(',').map(Number)]);
    tags.push(rowTags(row, ec));
  }

  if (lines.length === 0) {
    throw new Error(
      `${edgeTable.name}: none of its from/to values matched an id in ${nodeTable.name}. ` +
      'Check that both files use the same node identifiers.',
    );
  }
  if (ec.length !== undefined) {
    warnings.push('The edge table\'s length column was ignored; distances are recomputed from the coordinates so both algorithms see identical geometry.');
  }

  return { lines, tags, hasElevation, source: 'CSV nodes + edges' };
}

/** Build a tag bag from optional columns so the shared speed logic can use it. */
function rowTags(row, columns) {
  const tags = {};
  if (columns.speed !== undefined) {
    const v = row[columns.speed];
    if (v !== undefined && v !== '') tags.maxspeed = v;
  }
  if (columns.highway !== undefined) {
    const v = row[columns.highway];
    if (v !== undefined && v !== '') tags.highway = v;
  }
  if (columns.oneway !== undefined) {
    const v = row[columns.oneway];
    if (v !== undefined && v !== '') tags.oneway = v;
  }
  return tags;
}

/** Minimal RFC-4180-ish CSV reader. Handles quotes, escaped quotes and CRLF. */
export function parseCsv(text) {
  const clean = text.replace(/^\uFEFF/, '');
  const delimiter = detectDelimiter(clean);
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let i = 0; i < clean.length; i++) {
    const ch = clean[i];
    if (quoted) {
      if (ch === '"') {
        if (clean[i + 1] === '"') { field += '"'; i++; }
        else quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === delimiter) {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (ch !== '\r') {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  return rows.filter((r) => r.some((cell) => cell.trim() !== ''));
}

function detectDelimiter(text) {
  const firstLine = text.slice(0, text.indexOf('\n') === -1 ? text.length : text.indexOf('\n'));
  const candidates = [',', ';', '\t', '|'];
  let best = ',';
  let bestCount = -1;
  for (const candidate of candidates) {
    const count = firstLine.split(candidate).length - 1;
    if (count > bestCount) {
      bestCount = count;
      best = candidate;
    }
  }
  return best;
}

// ===========================================================================
//  Shared builder: lines → city map
// ===========================================================================

function buildMapFromLines(intermediate, ctx) {
  const { lines, tags, hasElevation } = intermediate;
  const warnings = ctx.warnings;

  if (!lines || lines.length === 0) {
    throw new Error('No road geometry found. Check that the file contains LineString features, OSM ways, or from/to coordinates.');
  }

  // ---- projection origin --------------------------------------------------
  let minLat = Infinity, maxLat = -Infinity, minLon = Infinity, maxLon = -Infinity;
  for (const line of lines) {
    for (const c of line) {
      if (c[1] < minLat) minLat = c[1];
      if (c[1] > maxLat) maxLat = c[1];
      if (c[0] < minLon) minLon = c[0];
      if (c[0] > maxLon) maxLon = c[0];
    }
  }
  if (!Number.isFinite(minLat)) throw new Error('No usable coordinates found.');

  const midLat = (minLat + maxLat) / 2;
  const mPerLat = METRES_PER_DEG_LAT;
  const mPerLon = METRES_PER_DEG_LAT * Math.cos((midLat * Math.PI) / 180);
  const projectX = (lon) => (lon - minLon) * mPerLon;
  const projectY = (lat) => (lat - minLat) * mPerLat;

  // ---- node store (snap coincident vertices together) ---------------------
  const nodeOf = new Map();
  const xs = [];
  const ys = [];
  const elevSum = [];
  const elevCount = [];

  const snap = ctx.snapMetres;
  const invSnap = 1 / snap;

  function nodeIndex(x, y, elev) {
    const ix = Math.round(x * invSnap);
    const iy = Math.round(y * invSnap);
    const key = (ix + KEY_OFFSET) * KEY_SPAN + (iy + KEY_OFFSET);
    let idx = nodeOf.get(key);
    if (idx === undefined) {
      idx = xs.length;
      xs.push(x);
      ys.push(y);
      elevSum.push(Number.isFinite(elev) ? elev : 0);
      elevCount.push(Number.isFinite(elev) ? 1 : 0);
      nodeOf.set(key, idx);
    } else if (Number.isFinite(elev)) {
      elevSum[idx] += elev;
      elevCount[idx]++;
    }
    return idx;
  }

  // ---- edges --------------------------------------------------------------
  const eFrom = [];
  const eTo = [];
  const eLen = [];
  const eSpeed = [];   // km/h, NaN when the file does not say
  const eDirected = [];
  const seen = new Set();

  let excludedHighways = 0;
  let duplicateSegments = 0;
  let zeroLength = 0;

  for (let li = 0; li < lines.length; li++) {
    let line = lines[li];
    const info = roadInfoFromTags(tags[li]);
    if (info.excluded) {
      excludedHighways++;
      continue;
    }
    if (info.reverse) line = line.slice().reverse();

    for (let i = 0; i + 1 < line.length; i++) {
      const a = line[i];
      const b = line[i + 1];
      const ax = projectX(a[0]);
      const ay = projectY(a[1]);
      const bx = projectX(b[0]);
      const by = projectY(b[1]);

      const na = nodeIndex(ax, ay, a[2]);
      const nb = nodeIndex(bx, by, b[2]);
      if (na === nb) continue;

      const length = Math.hypot(bx - ax, by - ay);
      if (!(length > 0)) { zeroLength++; continue; }

      const directed = info.oneway;
      const key = directed || na < nb
        ? na * KEY_SPAN + nb
        : nb * KEY_SPAN + na;
      if (seen.has(key)) { duplicateSegments++; continue; }
      seen.add(key);

      eFrom.push(na);
      eTo.push(nb);
      eLen.push(length);
      eSpeed.push(info.kph);
      eDirected.push(directed ? 1 : 0);
    }
  }

  const nodeCount = xs.length;
  const edgeCount = eFrom.length;
  if (nodeCount === 0 || edgeCount === 0) {
    throw new Error('The file produced no drivable roads. If it is an OSM extract, check that it contains highway ways.');
  }

  // ---- speeds and road classes -------------------------------------------
  const speedsWithValues = eSpeed.filter(Number.isFinite).length;
  const hasSpeeds = speedsWithValues > 0;

  if (!hasSpeeds) {
    // No speed information anywhere: mirror the synthetic generator by promoting the
    // longest 20 % of roads to arterials.
    const sorted = [...eLen].sort((x, y) => x - y);
    const threshold = sorted[Math.floor(sorted.length * 0.8)];
    for (let i = 0; i < edgeCount; i++) {
      eSpeed[i] = eLen[i] >= threshold ? ARTERIAL_SPEED * 3.6 : LOCAL_SPEED * 3.6;
    }
    warnings.push(
      'No speed limits found in the file — the longest 20 % of roads were treated as 60 km/h ' +
      'arterials and the rest as 40 km/h local streets.',
    );
  } else {
    let guessed = 0;
    for (let i = 0; i < edgeCount; i++) {
      if (!Number.isFinite(eSpeed[i])) {
        eSpeed[i] = LOCAL_SPEED * 3.6;
        guessed++;
      }
    }
    if (guessed > 0) {
      warnings.push(`${guessed} of ${edgeCount} roads had no speed information and were given 40 km/h.`);
    }
  }

  const speedMs = new Float64Array(edgeCount);
  const klass = new Uint8Array(edgeCount);
  for (let i = 0; i < edgeCount; i++) {
    const ms = Math.max(2, eSpeed[i] / 3.6);
    speedMs[i] = ms;
    klass[i] = ms >= (ARTERIAL_SPEED + LOCAL_SPEED) / 2 ? ROAD_CLASS.ARTERIAL : ROAD_CLASS.LOCAL;
  }

  // ---- connectivity: find the largest component --------------------------
  const dsu = new DSU(nodeCount);
  for (let i = 0; i < edgeCount; i++) dsu.union(eFrom[i], eTo[i]);

  const componentSize = new Map();
  for (let i = 0; i < nodeCount; i++) {
    const root = dsu.find(i);
    componentSize.set(root, (componentSize.get(root) || 0) + 1);
  }

  let mainRoot = -1;
  let mainSize = 0;
  for (const [root, size] of componentSize) {
    if (size > mainSize) { mainSize = size; mainRoot = root; }
  }

  const mainComponent = new Uint8Array(nodeCount);
  for (let i = 0; i < nodeCount; i++) {
    if (dsu.find(i) === mainRoot) mainComponent[i] = 1;
  }

  if (componentSize.size > 1) {
    warnings.push(
      `The network has ${componentSize.size} disconnected components; ${mainSize} of ${nodeCount} nodes ` +
      `(${(mainSize / nodeCount * 100).toFixed(1)} %) are in the largest one. The benchmark origin and ` +
      'destination are always drawn from that component, so a route always exists.',
    );
  }

  // ---- elevation ---------------------------------------------------------
  let elevation = null;
  if (hasElevation) {
    elevation = new Float64Array(nodeCount);
    for (let i = 0; i < nodeCount; i++) {
      elevation[i] = elevCount[i] > 0 ? elevSum[i] / elevCount[i] : 0;
    }
  }

  const stats = {
    excludedHighways,
    duplicateSegments,
    zeroLength,
    oneway: eDirected.reduce((sum, d) => sum + d, 0),
    components: componentSize.size,
    mainComponentSize: mainSize,
  };

  return {
    name: ctx.name,
    source: intermediate.source,
    nodeCount,
    edgeCount,
    hasElevation,
    x: Float64Array.from(xs),
    y: Float64Array.from(ys),
    elevation,
    edges: {
      from: Int32Array.from(eFrom),
      to: Int32Array.from(eTo),
      length: Float64Array.from(eLen),
      speed: speedMs,
      klass,
      directed: Uint8Array.from(eDirected),
    },
    mainComponent,
    stats,
    warnings: [...warnings],
  };
}

