/**
 * @returns {{excluded:boolean, oneway:boolean, reverse:boolean, kph:number, arterial:boolean}}
 */
function roadInfoFromTags(tags) {
  const result = { excluded: false, oneway: false, reverse: false, kph: NaN, arterial: false };
  if (!tags || typeof tags !== 'object') return result;

  const highway = typeof tags.highway === 'string' ? tags.highway.trim().toLowerCase() : '';
  if (highway) {
    if (EXCLUDED_HIGHWAYS.has(highway)) {
      result.excluded = true;
      return result;
    }
    result.arterial = ARTERIAL_HIGHWAYS.has(highway);
    if (HIGHWAY_SPEEDS_KPH[highway] !== undefined) result.kph = HIGHWAY_SPEEDS_KPH[highway];
  }

  if (tags.maxspeed !== undefined && tags.maxspeed !== null && tags.maxspeed !== '') {
    const parsed = parseMaxspeed(String(tags.maxspeed));
    if (Number.isFinite(parsed)) result.kph = parsed;
  }

  const oneway = tags.oneway;
  if (oneway !== undefined && oneway !== null) {
    const value = String(oneway).trim().toLowerCase();
    if (value === '-1' || value === 'reverse') {
      result.oneway = true;
      result.reverse = true;
    } else if (value === 'yes' || value === 'true' || value === '1') {
      result.oneway = true;
    }
  }
  if (String(tags.junction || '').toLowerCase() === 'roundabout') result.oneway = true;

  return result;
}

/** `"50"`, `"50 km/h"`, `"30 mph"`, `"30; 50"`, `"none"` → km/h or NaN. */
export function parseMaxspeed(value) {
  const match = /(\d+(?:\.\d+)?)\s*(mph|km\/h|kmh|kph|knots)?/i.exec(value);
  if (!match) return NaN;
  const number = Number(match[1]);
  if (!Number.isFinite(number)) return NaN;
  const unit = (match[2] || '').toLowerCase();
  if (unit === 'mph') return number * 1.609344;
  if (unit === 'knots') return number * 1.852;
  return number;
}
