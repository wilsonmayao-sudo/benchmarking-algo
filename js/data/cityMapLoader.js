/** Grid cell size used to merge coincident vertices, in metres. */
export const DEFAULT_SNAP_METRES = 0.5;

const METRES_PER_DEG_LAT = 111320;
const KEY_SPAN = 67108864;   // 2^26
const KEY_OFFSET = 33554432; // 2^25

/** Highway values that are not drivable and are dropped during import. */
const EXCLUDED_HIGHWAYS = new Set([
  'footway', 'path', 'steps', 'cycleway', 'pedestrian', 'bridleway', 'corridor',
  'construction', 'proposed', 'bus_guideway', 'raceway', 'platform', 'escape',
  'elevator', 'escalator', 'via_ferrata',
]);

/** Highway values treated as arterial roads when no maxspeed tag is present. */
const ARTERIAL_HIGHWAYS = new Set([
  'motorway', 'motorway_link', 'trunk', 'trunk_link', 'primary', 'primary_link',
  'secondary', 'secondary_link', 'tertiary', 'tertiary_link',
]);

/** Fallback speeds in km/h, used when a road has no maxspeed tag. */
const HIGHWAY_SPEEDS_KPH = {
  motorway: 90, motorway_link: 60,
  trunk: 70, trunk_link: 50,
  primary: 60, primary_link: 40,
  secondary: 50, secondary_link: 40,
  tertiary: 40, tertiary_link: 30,
  unclassified: 35, residential: 30, living_street: 15,
  service: 20, road: 30, track: 20,
};

