/**
 * Parse one or more uploaded files into a city map.
 *
 * @param {Array<{name:string, text:string}>} files
 * @param {{name?:string, snapMetres?:number}} [options]
 * @returns {{map:object, warnings:string[]}}
 */
export function parseCityMap(files, options = {}) {
  if (!files || files.length === 0) throw new Error('No file was selected.');

  const warnings = [];
  const ctx = {
    name: options.name || files[0].name.replace(/\.[^.]+$/, '') || 'City map',
    snapMetres: options.snapMetres || DEFAULT_SNAP_METRES,
    warnings,
  };

  let intermediate;
  if (files.length === 1) {
    const file = files[0];
    const head = file.text.replace(/^\uFEFF/, '').trimStart();
    if (head.startsWith('{') || head.startsWith('[')) {
      const json = parseJson(file.text, file.name);
      if (looksLikeOsm(json)) intermediate = osmToLines(json, warnings);
      else if (looksLikeGeoJson(json)) intermediate = geoJsonToLines(json, warnings);
      else {
        throw new Error(
          `${file.name}: the JSON is neither GeoJSON (no "features") nor Overpass/OSM ` +
          '(no "elements"). Export the road layer as GeoJSON, or save the Overpass response.',
        );
      }
    } else {
      intermediate = csvFilesToLines(files, warnings);
    }
  } else {
    intermediate = csvFilesToLines(files, warnings);
  }

  const map = buildMapFromLines(intermediate, ctx);
  return { map, warnings };
}

/**
 * Materialise a parsed city map into a fresh Graph.
 * A new graph is built for every scenario run so that traffic / elevation / closures
 * from a previous run can never leak into the next one.
 */
export function buildGraphFromMap(map) {
  const n = map.nodeCount;
  const m = map.edgeCount;
  const graph = new Graph(n, Math.max(32, m + 8));

  for (let i = 0; i < n; i++) {
    graph.x[i] = map.x[i];
    graph.y[i] = map.y[i];
    graph.elevation[i] = map.elevation ? map.elevation[i] : 0;
  }

  const { from, to, length, speed, klass, directed } = map.edges;
  for (let e = 0; e < m; e++) {
    graph.addEdge(from[e], to[e], length[e], speed[e], klass[e], directed[e] === 1);
  }

  return graph;
}

// ===========================================================================
//  Format detection
// ===========================================================================

function parseJson(text, fileName) {
  try {
    return JSON.parse(text.replace(/^\uFEFF/, ''));
  } catch (error) {
    throw new Error(`${fileName}: not valid JSON (${error.message}).`);
  }
}

function looksLikeOsm(json) {
  return !!json && Array.isArray(json.elements);
}

function looksLikeGeoJson(json) {
  if (!json || typeof json !== 'object') return false;
  if (json.type === 'FeatureCollection') return Array.isArray(json.features);
  if (json.type === 'Feature') return !!json.geometry;
  if (typeof json.type === 'string' && json.type.endsWith('String')) return true;
  return Array.isArray(json);
}

// ===========================================================================
//  GeoJSON
// ===========================================================================

function geoJsonToLines(json, warnings) {
  const features = toFeatureList(json);
  const lines = [];
  const tags = [];
  let hasElevation = false;
  let skippedPolygons = 0;

  for (const feature of features) {
    const geom = feature.geometry || feature;
    if (!geom || typeof geom.type !== 'string') continue;

    const parts = [];
    if (geom.type === 'LineString') {
      parts.push(geom.coordinates);
    } else if (geom.type === 'MultiLineString') {
      for (const c of geom.coordinates || []) parts.push(c);
    } else if (geom.type === 'Polygon' || geom.type === 'MultiPolygon') {
      skippedPolygons++;
      continue;
    } else {
      continue;
    }

    for (const coords of parts) {
      const line = [];
      for (const c of coords || []) {
        const lon = Number(c[0]);
        const lat = Number(c[1]);
        if (!Number.isFinite(lon) || !Number.isFinite(lat)) continue;
        const elev = c.length > 2 ? Number(c[2]) : NaN;
        if (Number.isFinite(elev)) hasElevation = true;
        line.push([lon, lat, elev]);
      }
      if (line.length < 2) continue;
      lines.push(line);
      tags.push(feature.properties || {});
    }
  }

  if (skippedPolygons > 0) {
    warnings.push(
      `${skippedPolygons} Polygon/MultiPolygon feature(s) were skipped — those are areas, ` +
      'not roads. Export the road layer as LineStrings.',
    );
  }

  return { lines, tags, hasElevation, source: 'GeoJSON' };
}

function toFeatureList(json) {
  if (Array.isArray(json)) return json.flatMap((entry) => toFeatureList(entry));
  if (json.type === 'FeatureCollection') return json.features || [];
  if (json.type === 'Feature') return [json];
  if (json.type === 'GeometryCollection') {
    return (json.geometries || []).map((geometry) => ({ geometry, properties: {} }));
  }
  return [{ geometry: json, properties: {} }];
}

// ===========================================================================
//  Overpass / OSM JSON
// ===========================================================================

function osmToLines(json, warnings) {
  const nodeById = new Map();
  for (const el of json.elements) {
    if (el && el.type === 'node' && Number.isFinite(el.lat) && Number.isFinite(el.lon)) {
      nodeById.set(el.id, el);
    }
  }

  const lines = [];
  const tags = [];
  let hasElevation = false;
  let missingGeometry = 0;

  for (const el of json.elements) {
    if (!el || el.type !== 'way') continue;

    const line = [];

    if (Array.isArray(el.geometry)) {
      // Overpass "out geom" — coordinates are inline on the way.
      for (const point of el.geometry) {
        const lat = Number(point.lat);
        const lon = Number(point.lon);
        if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
        line.push([lon, lat, NaN]);
      }
    } else if (Array.isArray(el.nodes)) {
      // Overpass "out body" — resolve node references.
      for (const id of el.nodes) {
        const node = nodeById.get(id);
        if (!node) continue;
        line.push([node.lon, node.lat, NaN]);
      }
    }

    if (line.length < 2) {
      missingGeometry++;
      continue;
    }
    lines.push(line);
    tags.push(el.tags || {});
  }

  if (missingGeometry > 0) {
    warnings.push(
      `${missingGeometry} way(s) had no usable geometry. Re-export with Overpass ` +
      '`out body; >; out skel qt;` or `out geom;` so node coordinates are included.',
    );
  }

  if (nodeById.size === 0 && lines.length === 0) {
    warnings.push('No node coordinates found — the file may have been queried with `out ids`.');
  }

  return { lines, tags, hasElevation, source: 'OSM JSON' };
}

